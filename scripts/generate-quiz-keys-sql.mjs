// Generates supabase/migrations/20261114120005_seed_quiz_answer_keys.sql from the
// TypeScript curriculum, so the server-side answer keys can never drift from
// the quiz content students see.
//
// Usage:  node scripts/generate-quiz-keys-sql.mjs
// Re-run after ANY change to quiz questions/options/correctAnswer, then re-run
// the regenerated migration in the Supabase SQL Editor (it is an upsert).

import { build } from 'esbuild';
import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';
import os from 'os';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'supabase', 'migrations', '20261114120005_seed_quiz_answer_keys.sql');

// Bundle just the data modules (they only import types) into a temp ES module.
const entry = `
  export { LEVEL_0_TOPICS } from ${JSON.stringify(path.join(root, 'src/data/level0TopicsData.ts'))};
  export { LEVEL_1_TOPICS } from ${JSON.stringify(path.join(root, 'src/data/level1TopicsData.ts'))};
  export { LEVEL_1_QUIZ_QUESTIONS } from ${JSON.stringify(path.join(root, 'src/data/mockData.ts'))};
`;
const result = await build({
  stdin: { contents: entry, resolveDir: root, loader: 'ts' },
  bundle: true, format: 'esm', platform: 'node', write: false, logLevel: 'error',
});
const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'aiw-quiz-')), 'data.mjs');
fs.writeFileSync(tmp, result.outputFiles[0].text);
const { LEVEL_0_TOPICS, LEVEL_1_TOPICS, LEVEL_1_QUIZ_QUESTIONS } = await import(pathToFileURL(tmp).href);

// level_id = COURSE_LEVELS.id  (1 = Level 1 Orientation, 2 = Level 2 Foundations)
const quizzes = [
  ...LEVEL_0_TOPICS.map(t => ({ id: t.quiz.id, level: 1, pass: t.quiz.passingScore, qs: t.quiz.questions })),
  ...LEVEL_1_TOPICS.map(t => ({ id: t.quiz.id, level: 2, pass: t.quiz.passingScore, qs: t.quiz.questions })),
  // Legacy PracticeQuizPage — existing 80 % pass rule.
  { id: 'foundations-practice-quiz', level: 2, pass: 80, qs: LEVEL_1_QUIZ_QUESTIONS },
];

// Sanity checks — fail loudly rather than emit a bad seed.
for (const z of quizzes) {
  const ids = new Set();
  for (const q of z.qs) {
    if (ids.has(q.id)) throw new Error(`${z.id}: duplicate question id ${q.id}`);
    ids.add(q.id);
    if (!Number.isInteger(q.correctAnswer) || q.correctAnswer < 0 || q.correctAnswer >= q.options.length) {
      throw new Error(`${z.id} Q${q.id}: correctAnswer ${q.correctAnswer} out of range`);
    }
  }
}

const lit = s => `'${String(s).replace(/'/g, "''")}'`;
const totalQ = quizzes.reduce((n, z) => n + z.qs.length, 0);
const dist = [0, 0, 0, 0];
quizzes.forEach(z => z.qs.forEach(q => dist[q.correctAnswer]++));

const sql = `-- =============================================================================
-- Migration 5 of 5 — Seed quiz definitions and answer keys
-- =============================================================================
-- GENERATED by scripts/generate-quiz-keys-sql.mjs — do not edit by hand.
-- Sources:
--   src/data/level0TopicsData.ts   (Level 1 Orientation topic quizzes)
--   src/data/level1TopicsData.ts   (Level 2 Foundations topic quizzes)
--   src/data/mockData.ts           (LEVEL_1_QUIZ_QUESTIONS → legacy PracticeQuizPage)
--
-- ${quizzes.length} quizzes, ${totalQ} questions. Correct-option distribution A/B/C/D: ${dist.join('/')}.
--
-- Re-runnable: ON CONFLICT ... DO UPDATE overwrites keys with the current
-- content. Questions removed from TypeScript are NOT deleted here.
-- =============================================================================

begin;

insert into private.quiz_definitions (quiz_id, level_id, pass_mark) values
${quizzes.map(z => `  (${lit(z.id)}, ${z.level}, ${z.pass})`).join(',\n')}
on conflict (quiz_id) do update
  set level_id  = excluded.level_id,
      pass_mark = excluded.pass_mark;

insert into private.quiz_answer_keys (quiz_id, question_id, correct_option, option_count) values
${quizzes.flatMap(z => z.qs.map(q => `  (${lit(z.id)}, ${q.id}, ${q.correctAnswer}, ${q.options.length})`)).join(',\n')}
on conflict (quiz_id, question_id) do update
  set correct_option = excluded.correct_option,
      option_count   = excluded.option_count;

commit;

-- Verification: expect ${quizzes.length} rows — 3 questions per topic quiz (pass 66),
-- 5 for foundations-practice-quiz (pass 80).
select d.quiz_id, d.level_id, d.pass_mark, count(k.*) as questions
  from private.quiz_definitions d
  left join private.quiz_answer_keys k using (quiz_id)
 group by d.quiz_id, d.level_id, d.pass_mark
 order by d.level_id, d.quiz_id;
`;

fs.writeFileSync(outFile, sql);
console.log(`Wrote ${path.relative(root, outFile)} — ${quizzes.length} quizzes, ${totalQ} keys, A/B/C/D = ${dist.join('/')}`);
